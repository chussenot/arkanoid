//! Renders BRYX's sound cues at build time with BRYX's fork of the Electric
//! Pulse engine (`audio/engine/`, see its PROVENANCE.md).
//!
//! Only with the `audio` feature (on by default):
//! 1. compile `audio/render.c` and the engine into a small host tool in
//!    `OUT_DIR`;
//! 2. render every `audio/cues/*.abc` to signed 16-bit mono at
//!    [`SAMPLE_RATE`], trim effects of trailing silence, and encode it to
//!    `OUT_DIR/<name>.ulaw`, 8-bit mu-law (`src/audio/mulaw.rs`);
//! 3. write `OUT_DIR/cues.rs`, a table of `(name, include_bytes!(...))` that
//!    `src/audio/cues.rs` includes;
//! 4. render every `audio/score/*.score` with BRYX's studio (float stereo,
//!    48 kHz; docs/design/orchestral-score.md) to QOA, `OUT_DIR/<name>.qoa`,
//!    and write `OUT_DIR/scores.rs`. A score named like a cue replaces that
//!    cue's ABC render in the game (`src/audio/cues.rs`, `studio`).
//!
//! So the engine is a build tool: the game binary carries rendered PCM and
//! runs no C. A cue is an `.abc` text file anyone can edit; rebuilding
//! re-renders it, deterministically.

#[cfg(feature = "audio")]
use std::path::{Path, PathBuf};
#[cfg(feature = "audio")]
use std::process::Command;

/// Matches `src/audio/cues.rs`'s `CUE_SAMPLE_RATE`. 22,050 Hz is the
/// engine's native rate: its chip voice is the sound of the thing, and it
/// keeps the embedded audio to one byte a sample at half CD rate.
#[cfg(feature = "audio")]
const SAMPLE_RATE: u32 = 22_050;

#[cfg(feature = "audio")]
const ENGINE_SOURCES: [&str; 12] = [
    "abc.c",
    "audio_dsp.c",
    "audio_engine.c",
    "audio_fx.c",
    "audio_mix.c",
    "audio_seq.c",
    "audio_song_builtin.c",
    // BRYX's studio: the float stereo renderer for `.score` files
    // (docs/design/orchestral-score.md).
    "studio.c",
    "studio_common.c",
    "studio_fx.c",
    "studio_sampler.c",
    "studio_synth.c",
];

#[cfg(feature = "audio")]
include!("src/audio/mulaw.rs");

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    compile_shaders();
    cue_meters();
    track_modes();
    #[cfg(feature = "audio")]
    render_cues();
}

/// The meter of the cues the effects land on (`src/cadence.rs`): each
/// one's bar length and beats per bar, read from its ABC header (`M:` and
/// `Q:`), so a visual that follows the music cannot drift from it when a
/// cue is rewritten. Text only: built with or without the `audio` feature.
fn cue_meters() {
    let mut out = String::from("// Generated by build.rs from audio/cues/*.abc. Do not edit.\n");
    for (name, file) in [("LEVEL_CLEAR", "level_clear"), ("WARP", "warp")] {
        // A studio score replaces the ABC cue (`render_scores`): its tempo
        // is the meter, four beats to its bar.
        let score = format!("audio/score/{file}.score");
        println!("cargo:rerun-if-changed={score}");
        if let Ok(text) = std::fs::read_to_string(&score) {
            let bpm: f64 = text
                .lines()
                .find_map(|l| l.strip_prefix("tempo 0 "))
                .and_then(|v| v.trim().parse().ok())
                .unwrap_or_else(|| panic!("{score}: no `tempo 0 <bpm>` line"));
            let bar = 4.0 * 60.0 / bpm;
            out.push_str(&format!(
                "pub const {name}: Meter = Meter {{ bar: {bar:?}, beats: 4 }};\n"
            ));
            continue;
        }
        let path = format!("audio/cues/{file}.abc");
        println!("cargo:rerun-if-changed={path}");
        let abc = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{path}: {e}"));
        let field = |key: &str| {
            abc.lines()
                .find_map(|l| l.strip_prefix(key))
                .map(str::trim)
                .unwrap_or_else(|| panic!("{path}: no {key} header"))
        };
        let ratio = |text: &str| -> f64 {
            let (n, d) = text.split_once('/').unwrap_or((text, "1"));
            n.trim().parse::<f64>().expect("meter numerator")
                / d.trim().parse::<f64>().expect("meter denominator")
        };
        // M:4/4 is the bar in whole notes; Q:1/4=160 is 160 quarter notes a
        // minute.
        let meter = field("M:");
        let beats: u32 = meter.split('/').next().unwrap().trim().parse().expect("M:");
        let (unit, bpm) = field("Q:").split_once('=').expect("Q: as unit=bpm");
        let bar = ratio(meter) * 60.0 / (ratio(unit) * bpm.trim().parse::<f64>().expect("Q: bpm"));
        out.push_str(&format!(
            "pub const {name}: Meter = Meter {{ bar: {bar:?}, beats: {beats} }};\n"
        ));
    }
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    std::fs::write(format!("{out_dir}/cue_meters.rs"), out).expect("write cue_meters.rs");
}

/// The mode each level track is written in, so the rally's scale
/// (`src/audio/director.rs`) follows a track when it is recomposed: the
/// `# mode E <mode>` line of its studio score (`audio/compose_studio.py`)
/// or, without one, the `% mode E <mode>,` line of its ABC cue
/// (`audio/compose.py`). Text only, like `cue_meters`.
fn track_modes() {
    let mut modes = Vec::new();
    for n in 1.. {
        let score = format!("audio/score/music_{n:02}.score");
        let path = format!("audio/cues/music_{n:02}.abc");
        println!("cargo:rerun-if-changed={score}");
        let (text, prefix, path) = match std::fs::read_to_string(&score) {
            Ok(text) => (text, "# mode E ", score),
            Err(_) => match std::fs::read_to_string(&path) {
                Ok(text) => (text, "% mode E ", path),
                Err(_) => break,
            },
        };
        println!("cargo:rerun-if-changed={path}");
        let mode = text
            .lines()
            .find_map(|l| l.strip_prefix(prefix))
            .and_then(|rest| rest.split(',').next())
            .unwrap_or_else(|| panic!("{path}: no `{prefix}<mode>` line"));
        modes.push(match mode.trim() {
            "dorian" => "Dorian",
            "aeolian" => "Aeolian",
            "phrygian" => "Phrygian",
            "harmonic" => "HarmonicMinor",
            other => panic!("{path}: unknown mode {other:?}"),
        });
    }
    let list: Vec<String> = modes.iter().map(|m| format!("Mode::{m}")).collect();
    let out = format!(
        "// Generated by build.rs from the level tracks' scores. Do not edit.\n\
         pub const LEVEL_MODES: &[Mode] = &[{}];\n",
        list.join(", ")
    );
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    std::fs::write(format!("{out_dir}/track_modes.rs"), out).expect("write track_modes.rs");
}

/// The effects' WESL shaders (`src/shaders/`), each entry module compiled
/// with its imports to one plain WGSL file in OUT_DIR, which `fx/gpu.rs`
/// `include_str!`s. Functions no entry point uses are stripped. A WESL
/// error fails the build with the compiler's own diagnostic.
fn compile_shaders() {
    println!("cargo:rerun-if-changed=src/shaders");
    for entry in ["fx_geometry", "bloom", "composite"] {
        let compiled = wesl::Compiler::default()
            .compile(format!("src/shaders/{entry}.wesl"))
            .inspect_err(|e| eprintln!("{e}"))
            .unwrap_or_else(|_| panic!("WESL: src/shaders/{entry}.wesl did not compile"));
        compiled.write_artifact(entry);
    }
}

#[cfg(feature = "audio")]
fn render_cues() {
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    println!("cargo:rerun-if-changed=audio");
    println!("cargo:rerun-if-changed=src/audio/mulaw.rs");

    let tool = compile_renderer(&out_dir);
    let studio = render_scores(&tool, &out_dir);
    let mut cues: Vec<PathBuf> = std::fs::read_dir("audio/cues")
        .expect("audio/cues")
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "abc"))
        .collect();
    cues.sort();

    let mut table = String::from(
        "// Generated by build.rs from audio/cues/*.abc. Do not edit.\n\
         pub const CUES: &[(&str, &[u8])] = &[\n",
    );
    for cue in &cues {
        let name = cue.file_stem().unwrap().to_str().unwrap().to_owned();
        if studio.replaced.contains(&name) {
            // Its studio render (QOA) plays instead (`src/audio/cues.rs`,
            // `studio`), so the ABC render is not embedded.
            table.push_str(&format!("    ({name:?}, &[]),\n"));
            continue;
        }
        let pcm = out_dir.join(format!("{name}.ulaw"));
        let mut samples: Vec<i16> = if let Some(effect) = studio.effects.get(&name) {
            // A studio effect, rendered at twice the cue rate: brought down
            // to it here, filtered so nothing above the new Nyquist folds.
            halve_rate(&read_s16(effect))
        } else {
            let wide = out_dir.join(format!("{name}.s16"));
            let status = Command::new(&tool)
                .arg(cue)
                .arg(&wide)
                .arg(SAMPLE_RATE.to_string())
                .status()
                .expect("run the cue renderer");
            assert!(status.success(), "rendering {} failed", cue.display());
            read_s16(&wide)
        };
        // Effects and stingers lose the silence the engine renders after
        // them (anything under one 8-bit step), so a voice frees itself the
        // moment its sound ends. Music loops keep their exact length: the
        // loop point depends on it.
        if !name.starts_with("music_") {
            while samples.last().is_some_and(|s| s.unsigned_abs() <= 256) {
                samples.pop();
            }
        }
        let bytes: Vec<u8> = samples.into_iter().map(mulaw_encode).collect();
        std::fs::write(&pcm, bytes).expect("write encoded cue");
        table.push_str(&format!(
            "    ({name:?}, include_bytes!({:?})),\n",
            pcm.display().to_string()
        ));
    }
    table.push_str("];\n");

    // The level tracks, music_01..music_NN, in order: what the game picks
    // from by level number, without a name lookup in the audio thread.
    let mut levels: Vec<String> = cues
        .iter()
        .filter_map(|c| c.file_stem()?.to_str().map(str::to_owned))
        .filter(|n| n.starts_with("music_") && n[6..].chars().all(|c| c.is_ascii_digit()))
        .collect();
    levels.sort();
    table.push_str("pub const LEVEL_MUSIC: &[&[u8]] = &[\n");
    for name in &levels {
        if studio.replaced.contains(name) {
            table.push_str("    &[],\n");
            continue;
        }
        let pcm = out_dir.join(format!("{name}.ulaw"));
        table.push_str(&format!(
            "    include_bytes!({:?}),\n",
            pcm.display().to_string()
        ));
    }
    table.push_str("];\n");
    std::fs::write(out_dir.join("cues.rs"), table).expect("write cues.rs");

    render_probes(&tool, &out_dir);
}

/// Signed 16-bit little-endian samples from a file.
#[cfg(feature = "audio")]
fn read_s16(path: &Path) -> Vec<i16> {
    std::fs::read(path)
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()))
        .as_chunks::<2>()
        .0
        .iter()
        .map(|&b| i16::from_le_bytes(b))
        .collect()
}

/// Stereo 16-bit at twice [`SAMPLE_RATE`] to mono at it: summed to mono,
/// low-passed (a 63-tap Blackman-windowed sinc, cut at 0.45 of the new
/// Nyquist's double, about 9.9 kHz) and every other sample kept.
#[cfg(feature = "audio")]
fn halve_rate(stereo: &[i16]) -> Vec<i16> {
    const TAPS: usize = 63;
    let mono: Vec<f64> = stereo
        .as_chunks::<2>()
        .0
        .iter()
        .map(|[l, r]| (f64::from(*l) + f64::from(*r)) * 0.5)
        .collect();
    let cut = 0.225; // cycles per input sample
    let mid = (TAPS / 2) as f64;
    let mut h: Vec<f64> = (0..TAPS)
        .map(|i| {
            let x = i as f64 - mid;
            let sinc = if x == 0.0 {
                2.0 * cut
            } else {
                (2.0 * std::f64::consts::PI * cut * x).sin() / (std::f64::consts::PI * x)
            };
            let w = 0.42 - 0.5 * (2.0 * std::f64::consts::PI * i as f64 / (TAPS - 1) as f64).cos()
                + 0.08 * (4.0 * std::f64::consts::PI * i as f64 / (TAPS - 1) as f64).cos();
            sinc * w
        })
        .collect();
    let sum: f64 = h.iter().sum();
    h.iter_mut().for_each(|v| *v /= sum);
    (0..mono.len() / 2)
        .map(|n| {
            let c = 2 * n;
            let acc: f64 = h
                .iter()
                .enumerate()
                .map(|(k, &w)| {
                    let i = c as isize + k as isize - mid as isize;
                    if i < 0 || i as usize >= mono.len() {
                        0.0
                    } else {
                        w * mono[i as usize]
                    }
                })
                .sum();
            acc.round().clamp(-32_768.0, 32_767.0) as i16
        })
        .collect()
}

/// What the studio rendered for the game: the cues its QOA renders
/// replace, and the effects it rendered for the mu-law path.
#[cfg(feature = "audio")]
struct StudioRenders {
    replaced: std::collections::HashSet<String>,
    effects: std::collections::HashMap<String, PathBuf>,
}

/// The studio's renders, in parallel:
/// - the scores (`audio/score/*.score`: music and stingers) to QOA for the
///   game, each replacing the ABC cue of its name;
/// - the effects (`audio/score/sfx/*.score`) to 16-bit stereo at twice
///   the cue rate, which `render_cues` brings down to the mu-law effects
///   path (effects are pitched by playback rate, so they stay there);
/// - the studio probes (`audio/probes/*.score`) to raw float stereo for
///   `src/audio/studio_probes.rs` (test code only: no probe reaches the
///   game).
///
/// A score takes seconds to render where an ABC cue takes milliseconds, and
/// any edit under `audio/` reruns this script, so each render is cached in
/// `OUT_DIR` under a key: the hash of the score and of everything a render
/// reads (instrument libraries, samples, the studio's sources). The studio
/// is deterministic, so an unchanged key is an unchanged render.
#[cfg(feature = "audio")]
fn render_scores(tool: &Path, out_dir: &Path) -> StudioRenders {
    use std::hash::{DefaultHasher, Hash, Hasher};
    use std::sync::atomic::{AtomicUsize, Ordering};

    let list = |dir: &str| -> Vec<PathBuf> {
        let mut found: Vec<PathBuf> = std::fs::read_dir(dir)
            .map(|d| {
                d.filter_map(|entry| entry.ok().map(|e| e.path()))
                    .filter(|path| path.extension().is_some_and(|ext| ext == "score"))
                    .collect()
            })
            .unwrap_or_default();
        found.sort();
        found
    };
    let stem = |path: &Path| path.file_stem().unwrap().to_str().unwrap().to_owned();
    let scores: Vec<(PathBuf, PathBuf)> = list("audio/score")
        .into_iter()
        .map(|s| {
            let out = out_dir.join(format!("{}.qoa", stem(&s)));
            (s, out)
        })
        .collect();
    let probes: Vec<(PathBuf, PathBuf)> = list("audio/probes")
        .into_iter()
        .map(|s| {
            let out = out_dir.join(format!("probe_{}.f32", stem(&s)));
            (s, out)
        })
        .collect();
    let effects: Vec<(PathBuf, PathBuf)> = list("audio/score/sfx")
        .into_iter()
        .map(|s| {
            let out = out_dir.join(format!("sfx_{}.s16", stem(&s)));
            (s, out)
        })
        .collect();
    let jobs: Vec<&(PathBuf, PathBuf)> = scores.iter().chain(&probes).chain(&effects).collect();
    let effect_rate = (2 * SAMPLE_RATE).to_string();

    let mut inputs = DefaultHasher::new();
    for root in [
        "audio/instruments",
        "audio/samples",
        "audio/engine",
        "audio/vendor",
    ] {
        hash_tree(Path::new(root), &mut inputs);
    }
    std::fs::read("audio/render.c")
        .expect("audio/render.c")
        .hash(&mut inputs);
    let inputs = inputs.finish();

    let next = AtomicUsize::new(0);
    let workers = std::thread::available_parallelism().map_or(4, |n| n.get());
    std::thread::scope(|scope| {
        for _ in 0..workers.min(jobs.len()) {
            scope.spawn(|| {
                while let Some((score, out)) = jobs.get(next.fetch_add(1, Ordering::Relaxed)) {
                    let key_file = out.with_extension("key");
                    let mut key = DefaultHasher::new();
                    inputs.hash(&mut key);
                    std::fs::read(score).expect("read score").hash(&mut key);
                    let key = format!("{:016x}", key.finish());
                    if out.exists() && std::fs::read_to_string(&key_file).is_ok_and(|k| k == key) {
                        continue;
                    }
                    let mut render = Command::new(tool);
                    render.arg(score).arg(out);
                    if out.extension().is_some_and(|e| e == "s16") {
                        render.arg(&effect_rate);
                    }
                    let status = render.status().expect("run the cue renderer");
                    assert!(status.success(), "rendering {} failed", score.display());
                    std::fs::write(&key_file, key).expect("write render key");
                }
            });
        }
    });

    let table = |header: &str, name: &str, list: &[(PathBuf, PathBuf)]| {
        let mut t = format!("// Generated by build.rs from {header}. Do not edit.\npub const {name}: &[(&str, &[u8])] = &[\n");
        for (score, out) in list {
            t.push_str(&format!(
                "    ({:?}, include_bytes!({:?})),\n",
                stem(score),
                out.display().to_string()
            ));
        }
        t.push_str("];\n");
        t
    };
    std::fs::write(
        out_dir.join("scores.rs"),
        table("audio/score/*.score", "STUDIO", &scores),
    )
    .expect("write scores.rs");
    std::fs::write(
        out_dir.join("studio_probes.rs"),
        table("audio/probes/*.score", "STUDIO_PROBES", &probes),
    )
    .expect("write studio_probes.rs");
    StudioRenders {
        replaced: scores.iter().map(|(s, _)| stem(s)).collect(),
        effects: effects
            .into_iter()
            .map(|(s, out)| (stem(&s), out))
            .collect(),
    }
}

/// Hashes every file under `dir`, in name order, with its path.
#[cfg(feature = "audio")]
fn hash_tree(dir: &Path, hasher: &mut std::hash::DefaultHasher) {
    use std::hash::Hash;
    let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)
        .map(|d| d.filter_map(|e| e.ok().map(|e| e.path())).collect())
        .unwrap_or_default();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            hash_tree(&path, hasher);
        } else if let Ok(bytes) = std::fs::read(&path) {
            path.hash(hasher);
            bytes.hash(hasher);
        }
    }
}

/// The engine probes (`audio/probes/*.abc`): rendered to raw 16-bit next to
/// the cues, for `src/audio/probes.rs` to check the engine fork's features.
/// Only test code names `probes.rs`, so no probe reaches the game binary.
#[cfg(feature = "audio")]
fn render_probes(tool: &Path, out_dir: &Path) {
    let mut probes: Vec<PathBuf> = std::fs::read_dir("audio/probes")
        .expect("audio/probes")
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "abc"))
        .collect();
    probes.sort();
    let mut table = String::from(
        "// Generated by build.rs from audio/probes/*.abc. Do not edit.\n\
         pub const PROBES: &[(&str, &[u8])] = &[\n",
    );
    for probe in &probes {
        let name = probe.file_stem().unwrap().to_str().unwrap().to_owned();
        let pcm = out_dir.join(format!("probe_{name}.s16"));
        let status = Command::new(tool)
            .arg(probe)
            .arg(&pcm)
            .arg(SAMPLE_RATE.to_string())
            .status()
            .expect("run the cue renderer");
        assert!(status.success(), "rendering {} failed", probe.display());
        table.push_str(&format!(
            "    ({name:?}, include_bytes!({:?})),\n",
            pcm.display().to_string()
        ));
    }
    table.push_str("];\n");
    std::fs::write(out_dir.join("probes.rs"), table).expect("write probes.rs");
}

/// Builds `audio/render.c` and the engine into an executable for the
/// *host* (it runs here, during the build), with whatever C compiler `cc`
/// finds. `cc` normally builds libraries for the target; asking it for the
/// host's compiler and driving that compiler directly is the small step
/// from there to a tool.
#[cfg(feature = "audio")]
fn compile_renderer(out_dir: &Path) -> PathBuf {
    let host = std::env::var("HOST").expect("HOST");
    let compiler = cc::Build::new()
        .host(&host)
        .target(&host)
        .opt_level(2)
        .get_compiler();
    let exe = out_dir.join(if cfg!(windows) {
        "bryx-cue-render.exe"
    } else {
        "bryx-cue-render"
    });
    let mut cmd = compiler.to_command();
    let mut sources = vec![PathBuf::from("audio/render.c")];
    sources.extend(
        ENGINE_SOURCES
            .iter()
            .map(|f| Path::new("audio/engine").join(f)),
    );
    if compiler.is_like_msvc() {
        cmd.arg("/nologo")
            .arg("/Iaudio/engine")
            .arg(format!("/Fo{}\\", out_dir.display()))
            .args(&sources)
            .arg(format!("/Fe{}", exe.display()));
    } else {
        cmd.arg("-std=c99")
            .arg("-D_DEFAULT_SOURCE")
            .arg("-D_XOPEN_SOURCE=600")
            .arg("-Iaudio/engine")
            .args(&sources)
            .arg("-o")
            .arg(&exe)
            .arg("-lm");
    }
    let status = cmd.status().expect("run the C compiler");
    assert!(
        status.success(),
        "compiling the audio cue renderer failed (a C compiler is needed \
         for the default `audio` feature; build with --no-default-features \
         to skip audio)"
    );
    exe
}
