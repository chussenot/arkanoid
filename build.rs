//! Renders BRYX's sound cues at build time with BRYX's fork of the Electric
//! Pulse engine (`audio/engine/`, see its PROVENANCE.md).
//!
//! Only with the `audio` feature (on by default):
//! 1. compile `audio/render.c` and the engine into a small host tool in
//!    `OUT_DIR`;
//! 2. render every `audio/cues/*.abc` to signed 16-bit mono at
//!    [`SAMPLE_RATE`], trim effects of trailing silence, and encode it to
//!    `OUT_DIR/<name>.ulaw`, 8-bit mu-law (`src/audio/mulaw.rs`);
//! 3. write `OUT_DIR/cues.rs`, a table of `(name, include_bytes!(...))` that
//!    `src/audio/cues.rs` includes.
//!
//! So the engine is a build tool: the game binary carries rendered PCM and
//! runs no C. A cue is an `.abc` text file anyone can edit; rebuilding
//! re-renders it, deterministically.

#[cfg(feature = "audio")]
use std::path::{Path, PathBuf};
#[cfg(feature = "audio")]
use std::process::Command;

/// Matches `src/audio/cues.rs`'s `CUE_SAMPLE_RATE`. 22,050 Hz is the
/// engine's native rate: its chip voice is the sound of the thing, and it
/// keeps the embedded audio to one byte a sample at half CD rate.
#[cfg(feature = "audio")]
const SAMPLE_RATE: u32 = 22_050;

#[cfg(feature = "audio")]
const ENGINE_SOURCES: [&str; 7] = [
    "abc.c",
    "audio_dsp.c",
    "audio_engine.c",
    "audio_fx.c",
    "audio_mix.c",
    "audio_seq.c",
    "audio_song_builtin.c",
];

#[cfg(feature = "audio")]
include!("src/audio/mulaw.rs");

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    #[cfg(feature = "audio")]
    render_cues();
}

#[cfg(feature = "audio")]
fn render_cues() {
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    println!("cargo:rerun-if-changed=audio");
    println!("cargo:rerun-if-changed=src/audio/mulaw.rs");

    let tool = compile_renderer(&out_dir);
    let mut cues: Vec<PathBuf> = std::fs::read_dir("audio/cues")
        .expect("audio/cues")
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "abc"))
        .collect();
    cues.sort();

    let mut table = String::from(
        "// Generated by build.rs from audio/cues/*.abc. Do not edit.\n\
         pub const CUES: &[(&str, &[u8])] = &[\n",
    );
    for cue in &cues {
        let name = cue.file_stem().unwrap().to_str().unwrap().to_owned();
        let wide = out_dir.join(format!("{name}.s16"));
        let pcm = out_dir.join(format!("{name}.ulaw"));
        let status = Command::new(&tool)
            .arg(cue)
            .arg(&wide)
            .arg(SAMPLE_RATE.to_string())
            .status()
            .expect("run the cue renderer");
        assert!(status.success(), "rendering {} failed", cue.display());
        let mut samples: Vec<i16> = std::fs::read(&wide)
            .expect("read rendered cue")
            .as_chunks::<2>()
            .0
            .iter()
            .map(|&b| i16::from_le_bytes(b))
            .collect();
        // Effects and stingers lose the silence the engine renders after
        // them (anything under one 8-bit step), so a voice frees itself the
        // moment its sound ends. Music loops keep their exact length: the
        // loop point depends on it.
        if !name.starts_with("music_") {
            while samples.last().is_some_and(|s| s.unsigned_abs() <= 256) {
                samples.pop();
            }
        }
        let bytes: Vec<u8> = samples.into_iter().map(mulaw_encode).collect();
        std::fs::write(&pcm, bytes).expect("write encoded cue");
        table.push_str(&format!(
            "    ({name:?}, include_bytes!({:?})),\n",
            pcm.display().to_string()
        ));
    }
    table.push_str("];\n");

    // The level tracks, music_01..music_NN, in order: what the game picks
    // from by level number, without a name lookup in the audio thread.
    let mut levels: Vec<String> = cues
        .iter()
        .filter_map(|c| c.file_stem()?.to_str().map(str::to_owned))
        .filter(|n| n.starts_with("music_") && n[6..].chars().all(|c| c.is_ascii_digit()))
        .collect();
    levels.sort();
    table.push_str("pub const LEVEL_MUSIC: &[&[u8]] = &[\n");
    for name in &levels {
        let pcm = out_dir.join(format!("{name}.ulaw"));
        table.push_str(&format!(
            "    include_bytes!({:?}),\n",
            pcm.display().to_string()
        ));
    }
    table.push_str("];\n");
    std::fs::write(out_dir.join("cues.rs"), table).expect("write cues.rs");
}

/// Builds `audio/render.c` and the engine into an executable for the
/// *host* (it runs here, during the build), with whatever C compiler `cc`
/// finds. `cc` normally builds libraries for the target; asking it for the
/// host's compiler and driving that compiler directly is the small step
/// from there to a tool.
#[cfg(feature = "audio")]
fn compile_renderer(out_dir: &Path) -> PathBuf {
    let host = std::env::var("HOST").expect("HOST");
    let compiler = cc::Build::new()
        .host(&host)
        .target(&host)
        .opt_level(2)
        .get_compiler();
    let exe = out_dir.join(if cfg!(windows) {
        "bryx-cue-render.exe"
    } else {
        "bryx-cue-render"
    });
    let mut cmd = compiler.to_command();
    let mut sources = vec![PathBuf::from("audio/render.c")];
    sources.extend(
        ENGINE_SOURCES
            .iter()
            .map(|f| Path::new("audio/engine").join(f)),
    );
    if compiler.is_like_msvc() {
        cmd.arg("/nologo")
            .arg("/Iaudio/engine")
            .arg(format!("/Fo{}\\", out_dir.display()))
            .args(&sources)
            .arg(format!("/Fe{}", exe.display()));
    } else {
        cmd.arg("-std=c99")
            .arg("-D_DEFAULT_SOURCE")
            .arg("-D_XOPEN_SOURCE=600")
            .arg("-Iaudio/engine")
            .args(&sources)
            .arg("-o")
            .arg(&exe)
            .arg("-lm");
    }
    let status = cmd.status().expect("run the C compiler");
    assert!(
        status.success(),
        "compiling the audio cue renderer failed (a C compiler is needed \
         for the default `audio` feature; build with --no-default-features \
         to skip audio)"
    );
    exe
}
